// Builds fonts/fontawesome-subset.css plus trimmed Font Awesome 6.4.0 fonts holding only the icons the public
// pages use (about 20 KB instead of about 270 KB from the CDN). Admin pages keep the full CDN stylesheet.
//
// Re-run after adding an icon to a public page, or the new icon shows as a blank square:
//   pip install fonttools brotli
//   node tools/fontawesome-subset.mjs            (set PYTHON=... if "python" isn't the one with fonttools)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CDN = 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0';
const PAGES = ['index', 'about', 'services', 'resources', 'events', 'join', 'donate', 'sponsors', 'contact', 'directory',
  'member', 'privacy', 'terms', 'refunds', '404'].map((p) => `${p}.html`)
  .concat(['script.js', 'member-common.js', 'account-status.js']);
const FONTS = { 'fa-solid-900': 'Font Awesome 6 Free', 'fa-brands-400': 'Font Awesome 6 Brands' };

// Every fa-* name on the public pages (icon names and helpers such as fa-spin; helpers are kept anyway).
const used = new Set();
for (const f of PAGES) {
  for (const m of fs.readFileSync(path.join(ROOT, f), 'utf8').matchAll(/\bfa-[a-z0-9-]+/g)) used.add(m[0]);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fa-'));
async function download(file) {
  const res = await fetch(`${CDN}/${file}`);
  if (!res.ok) throw new Error(`${file}: ${res.status}`);
  const out = path.join(tmp, path.basename(file));
  fs.writeFileSync(out, Buffer.from(await res.arrayBuffer()));
  return out;
}
const css = fs.readFileSync(await download('css/all.min.css'), 'utf8');

// Split the minified stylesheet into top-level rules: [{ prelude, body }].
const header = css.match(/^\/\*![\s\S]*?\*\//)[0];
const rules = [];
for (let i = header.length, start = i, depth = 0, open = -1; i < css.length; i++) {
  if (css[i] === '{' && depth++ === 0) open = i;
  if (css[i] === '}' && --depth === 0) {
    rules.push({ prelude: css.slice(start, open).trim(), body: css.slice(open + 1, i) });
    start = i + 1;
  }
}

const ICON_RULE = /^(\.fa-[a-z0-9-]+:(?:before|after),?)+$/;
const codepoints = new Set();
const kept = [];
for (const { prelude, body } of rules) {
  if (prelude === '@font-face') {
    const font = Object.keys(FONTS).find((f) => body.includes(`webfonts/${f}.woff2`) && body.includes(`"${FONTS[f]}"`));
    if (font) kept.push(`@font-face{${body.replace(/src:[^;}]+/, `src:url(${font}.woff2) format("woff2")`)}}`);
    continue; // regular, v4 and v5 shims aren't used
  }
  if (ICON_RULE.test(prelude) && /^content:"\\[0-9a-f]+"$/.test(body)) {
    const selectors = prelude.split(',').filter((s) => used.has(s.replace(/^\.|:(before|after)$/g, '')));
    if (!selectors.length) continue;
    codepoints.add(`U+${body.match(/\\([0-9a-f]+)/)[1]}`);
    kept.push(`${selectors.join(',')}{${body}}`);
    continue;
  }
  kept.push(`${prelude}{${body}}`);
}

const outDir = path.join(ROOT, 'fonts');
fs.mkdirSync(outDir, { recursive: true });
const python = process.env.PYTHON || 'python';
for (const font of Object.keys(FONTS)) {
  execFileSync(python, ['-m', 'fontTools.subset', await download(`webfonts/${font}.woff2`),
    `--unicodes=${[...codepoints].join(',')}`, '--flavor=woff2', '--layout-features=*',
    `--output-file=${path.join(outDir, `${font}.woff2`)}`], { stdio: 'inherit' });
}
fs.writeFileSync(path.join(outDir, 'fontawesome-subset.css'),
  `${header}\n/* Generated by tools/fontawesome-subset.mjs: only the icons used on the public pages. */\n${kept.join('')}\n`);

const missing = [...used].filter((n) => !kept.some((r) => r.includes(`${n}:before`) || r.includes(`${n}{`) || r.includes(`${n},`)));
console.log(`${codepoints.size} icons kept. Not in Font Awesome Free 6.4.0: ${missing.join(', ') || 'none'}`);
for (const f of fs.readdirSync(outDir)) console.log(`  fonts/${f}  ${Math.round(fs.statSync(path.join(outDir, f)).size / 1024)} KB`);
fs.rmSync(tmp, { recursive: true, force: true });
