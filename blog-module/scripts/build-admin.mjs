// Builds the static admin editor into a folder your web server serves.
//
//   node --experimental-strip-types blog-module/scripts/build-admin.mjs [outDir]
//
// outDir defaults to public/<adminPath> (Next.js and most static hosts).
// Copies admin/*.{html,css,js} and writes config.js from blog.config.ts, so
// the editor's settings come from the same single config file.

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const moduleDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { default: config } = await import(pathToFileURL(path.join(moduleDir, 'blog.config.ts')).href);

const outDir = path.resolve(process.argv[2] || path.join('public', config.adminPath.replace(/^\/+/, '')));
await mkdir(outDir, { recursive: true });

for (const file of ['admin.css', 'admin.js']) {
  await copyFile(path.join(moduleDir, 'admin', file), path.join(outDir, file));
}

// Absolute asset paths, so the page works at /blog-admin with or without a
// trailing slash.
const html = await readFile(path.join(moduleDir, 'admin', 'index.html'), 'utf8');
await writeFile(
  path.join(outDir, 'index.html'),
  html.replace(/(href|src)="(admin\.css|admin\.js|config\.js)"/g, `$1="${config.adminPath}/$2"`),
);

// Only what the browser needs; everything here is public anyway.
const browserConfig = {
  siteName: config.siteName,
  siteUrl: config.siteUrl,
  basePath: config.basePath,
  logoUrl: config.logoUrl,
  defaultAuthor: config.defaultAuthor,
  firebase: config.firebase,
};
await writeFile(
  path.join(outDir, 'config.js'),
  `// Generated by blog-module/scripts/build-admin.mjs from blog.config.ts. Do not edit.\nwindow.BLOG_CONFIG = ${JSON.stringify(browserConfig, null, 2)};\n`,
);

console.log(`Blog admin built to ${path.relative(process.cwd(), outDir) || '.'}`);
